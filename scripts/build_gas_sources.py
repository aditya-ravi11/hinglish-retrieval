"""Write form_gas/Sources.js from data/sources/sources.jsonl.

The Apps Script form needs the source queries as a JS array:
[source_id, lang, text, priority]. Roles are left out on purpose: the form
treats every query the same.

Usage: python scripts/build_gas_sources.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    rows = [json.loads(l) for l in open(ROOT / "data/sources/sources.jsonl", encoding="utf-8")]
    items = [[r["source_id"], r["lang"], r["text"], r["priority"]] for r in rows]
    body = ",\n".join(json.dumps(x, ensure_ascii=False) for x in items)
    out = ROOT / "form_gas" / "Sources.js"
    out.write_text(
        "// Generated by scripts/build_gas_sources.py from data/sources/sources.jsonl. Do not edit.\n"
        f"var SOURCES = [\n{body}\n];\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"wrote {len(items)} sources to {out}")


if __name__ == "__main__":
    main()
